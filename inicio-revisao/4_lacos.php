<?php

// Laço FOR - Exemplo alicado em Tabuada
for ($i = 1; $i <= 10; $i++) {
    echo "8 x $i = " . (8 * $i) . "<br>";
}

// While - (Enquanto) Contagem regressiva
echo "<br>";
$n = 10;
while ($n >= 0) {
    echo $n . "<br>";
    $n--;
}

// Do While - (Faça enquanto) Executa ao menos 1 vez

echo "<br>";
$j = 10;
do {
    echo "j vale: $j <br>";
    $j--;
} while ($j >= 0);
